using System.Diagnostics.CodeAnalysis;

namespace PdfOxide
{
    /// <summary>
    /// An image supplied either as a file path or as encoded image bytes.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A <see langword="string"/> converts to the path case and a
    /// <see cref="byte"/> array converts to the encoded-data case, so APIs that
    /// accept either shape can expose a single parameter:
    /// </para>
    /// <code>
    /// PdfImageSource logo = "logo.png";
    /// PdfImageSource preview = File.ReadAllBytes("preview.png");
    /// page.Image(logo, new PdfRect(72, 200, 64, 64));
    /// </code>
    /// <para>
    /// The type is a C# union. It carries exactly one of the two case values and
    /// supports exhaustive type-pattern matching, but it is not a collection and
    /// has no equality members.
    /// </para>
    /// </remarks>
    [SuppressMessage(
        "Performance",
        "CA1815:Override equals and operator equals on value types",
        Justification = "Union matching is generated by the compiler; equality is intentionally not part of the union contract.")]
    public union PdfImageSource(string, byte[]);
}
